#!/usr/bin/env node
/**
 * Syncs pure TypeScript vocabulary, conjugation, adverb, preposition, story,
 * crossword, scene-theme, and market-item data from ../Portugese-for-Kids
 * into src/core/ and src/data/marketItems.mobile.ts.
 *
 * Usage:
 *   node scripts/sync-core.mjs              # sync and update core.lock.json
 *   node scripts/sync-core.mjs --check      # verify zero drift (CI)
 *   node scripts/sync-core.mjs --source dir # override web repo path
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const MOBILE_ROOT = path.resolve(__dirname, '..');

const args = process.argv.slice(2);
const CHECK_MODE = args.includes('--check');
const VERIFY_LOCK_MODE = args.includes('--verify-lock');
const sourceFlagIdx = args.indexOf('--source');
const WEB_ROOT = path.resolve(
  MOBILE_ROOT,
  sourceFlagIdx !== -1 && args[sourceFlagIdx + 1]
    ? args[sourceFlagIdx + 1]
    : '../Portugese-for-Kids',
);

const HEADER = '// GENERATED BY scripts/sync-core.mjs — DO NOT EDIT BY HAND.\n';
const FORBIDDEN_PATTERNS = [
  /\bimport\.meta\b/,
  /\bwindow\./,
  /\bdocument\./,
  /\blocalStorage\b/,
];

const DIRECT_COPIES = [
  ['src/data/types.ts', 'src/core/data/types.ts'],
  ['src/data/words.ts', 'src/core/data/words.ts'],
  ['src/data/verbConjugations.ts', 'src/core/data/verbConjugations.ts'],
  ['src/data/adverbData.ts', 'src/core/data/adverbData.ts'],
  ['src/data/prepGroups.ts', 'src/core/data/prepGroups.ts'],
  ['src/data/storyData.ts', 'src/core/data/storyData.ts'],
  ['src/utils/crosswordGenerator.ts', 'src/core/utils/crosswordGenerator.ts'],
  ['src/story/sceneTheme.ts', 'src/core/story/sceneTheme.ts'],
];

export const MOBILE_EXCLUDED_MARKET_ITEMS = ['wine', 'beer'];

function sha256(content) {
  return crypto.createHash('sha256').update(content, 'utf8').digest('hex');
}

function readWebFile(relPath) {
  const fullPath = path.join(WEB_ROOT, relPath);
  if (!fs.existsSync(fullPath)) {
    throw new Error(`Missing source file in web repo: ${fullPath}`);
  }
  return fs.readFileSync(fullPath, 'utf8');
}

function buildStoryTopics(aiSource) {
  const typeMatch = aiSource.match(/export type StoryContext =[\s\S]*?;\n/);
  if (!typeMatch) {
    throw new Error('Could not extract `export type StoryContext` from src/utils/ai.ts');
  }
  const topicsMatch = aiSource.match(
    /(?:export\s+)?const CONTEXT_TOPICS:\s*Record<StoryContext,\s*readonly string\[\]>\s*=[\s\S]*?\n\};/,
  );
  if (!topicsMatch) {
    throw new Error('Could not extract `CONTEXT_TOPICS` from src/utils/ai.ts');
  }
  const exportedTopics = topicsMatch[0].startsWith('export ')
    ? topicsMatch[0]
    : `export ${topicsMatch[0]}`;

  return `${HEADER}\n${typeMatch[0]}\n${exportedTopics}\n`;
}

function buildCoreDataIndex() {
  return `${HEADER}export * from './types';
export * from './words';
export * from './storyData';
export * from './prepGroups';
export * from './adverbData';
export * from './verbConjugations';
export * from './storyTopics';
export {
  marketItems,
  MOBILE_EXCLUDED_MARKET_ITEMS,
  type MobileMarketItem,
} from '../../data/marketItems.mobile';
`;
}

function buildMobileMarketItems(marketSource) {
  const itemsDir = path.join(MOBILE_ROOT, 'assets', 'items');
  const availablePngs = new Set(
    fs
      .readdirSync(itemsDir)
      .filter((file) => file.endsWith('.png'))
      .map((file) => file.slice(0, -4)),
  );
  if (availablePngs.size === 0) {
    throw new Error(`No pre-rasterized item PNGs found in ${itemsDir}`);
  }

  const excludedSet = new Set(MOBILE_EXCLUDED_MARKET_ITEMS);
  const transformedBody = [];
  const referencedAssets = new Set();

  // Strip top MarketItem import; split into chunks so multi-line `{ ... }` entries work.
  const withoutImport = marketSource
    .replace(/^import type \{ MarketItem \}[^\n]*\n+/m, '')
    .replace('export const marketItems: MarketItem[]', 'export const marketItems: MobileMarketItem[]');

  const lines = withoutImport.split('\n');
  let buffer = [];
  let inItem = false;
  let braceDepth = 0;

  const flushItem = (entryLines) => {
    const joined = entryLines.join('\n');
    const idMatch = joined.match(/\bid:\s*'([^']+)'/);
    if (idMatch && excludedSet.has(idMatch[1])) {
      return;
    }
    const rewritten = joined.replace(
      /iconSrc:\s*`\$\{import\.meta\.env\.BASE_URL\}items\/([a-z0-9_]+)\.svg`/gi,
      (_, name) => {
        if (!availablePngs.has(name)) {
          throw new Error(
            `Missing rasterized PNG asset assets/items/${name}.png required by marketItems.ts`,
          );
        }
        referencedAssets.add(name);
        return `iconAsset: MARKET_ITEM_ASSETS['${name}']`;
      },
    );
    transformedBody.push(rewritten);
  };

  for (const line of lines) {
    const trimmed = line.trim();
    if (!inItem && trimmed.startsWith('{')) {
      inItem = true;
      braceDepth = (line.match(/\{/g)?.length ?? 0) - (line.match(/\}/g)?.length ?? 0);
      buffer = [line];
      if (braceDepth <= 0) {
        flushItem(buffer);
        buffer = [];
        inItem = false;
      }
      continue;
    }
    if (inItem) {
      buffer.push(line);
      braceDepth += (line.match(/\{/g)?.length ?? 0) - (line.match(/\}/g)?.length ?? 0);
      if (braceDepth <= 0) {
        flushItem(buffer);
        buffer = [];
        inItem = false;
      }
      continue;
    }
    transformedBody.push(line);
  }

  const assetEntries = [...referencedAssets]
    .sort()
    .map((name) => `  ${name}: require('../../assets/items/${name}.png'),`)
    .join('\n');

  const preamble = `${HEADER}import type { ImageSourcePropType } from 'react-native';
import type { MarketItem } from '../core/data/types';

export type MobileMarketItem = Omit<MarketItem, 'iconSrc'> & {
  iconAsset?: ImageSourcePropType;
};

export const MOBILE_EXCLUDED_MARKET_ITEMS = ['wine', 'beer'] as const;

const MARKET_ITEM_ASSETS: Record<string, ImageSourcePropType> = {
${assetEntries}
};

`;

  return `${preamble}${transformedBody.join('\n').trimStart()}\n`;
}

function assertCleanMobileSource(relPath, content) {
  if (/\bimport\.meta\b/.test(content)) {
    throw new Error(
      `Forbidden web-only pattern /\\bimport\\.meta\\b/ found in synced file: ${relPath}`,
    );
  }
  const withoutCommentsOrStrings = content
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/'(?:\\.|[^'\\])*'/g, "''")
    .replace(/"(?:\\.|[^"\\])*"/g, '""')
    .replace(/`(?:\\.|[^`$\\]|\$(?!\{))*`/g, '``');
  for (const pattern of FORBIDDEN_PATTERNS) {
    if (pattern.test(withoutCommentsOrStrings)) {
      throw new Error(
        `Forbidden web-only pattern ${pattern} found in synced file: ${relPath}`,
      );
    }
  }
}

function generateOutputs() {
  const sourceHashes = {};
  const generated = new Map();

  for (const [srcRel, dstRel] of DIRECT_COPIES) {
    const raw = readWebFile(srcRel);
    sourceHashes[srcRel] = sha256(raw);
    const out = `${HEADER}${raw}`;
    assertCleanMobileSource(dstRel, out);
    generated.set(dstRel, out);
  }

  const aiRaw = readWebFile('src/utils/ai.ts');
  sourceHashes['src/utils/ai.ts'] = sha256(aiRaw);
  const storyTopics = buildStoryTopics(aiRaw);
  assertCleanMobileSource('src/core/data/storyTopics.ts', storyTopics);
  generated.set('src/core/data/storyTopics.ts', storyTopics);

  const marketRaw = readWebFile('src/data/marketItems.ts');
  sourceHashes['src/data/marketItems.ts'] = sha256(marketRaw);
  const mobileMarket = buildMobileMarketItems(marketRaw);
  assertCleanMobileSource('src/data/marketItems.mobile.ts', mobileMarket);
  generated.set('src/data/marketItems.mobile.ts', mobileMarket);

  const indexOut = buildCoreDataIndex();
  assertCleanMobileSource('src/core/data/index.ts', indexOut);
  generated.set('src/core/data/index.ts', indexOut);

  const outputHashes = {};
  for (const [relPath, content] of [...generated.entries()].sort((a, b) =>
    a[0].localeCompare(b[0]),
  )) {
    outputHashes[relPath] = sha256(content);
  }

  const lockJson = `${JSON.stringify(
    {
      version: 1,
      excludedMarketItems: MOBILE_EXCLUDED_MARKET_ITEMS,
      sources: Object.fromEntries(
        Object.entries(sourceHashes).sort((a, b) => a[0].localeCompare(b[0])),
      ),
      outputs: outputHashes,
    },
    null,
    2,
  )}\n`;

  generated.set('core.lock.json', lockJson);
  return generated;
}

function verifyLockFile() {
  const lockPath = path.join(MOBILE_ROOT, 'core.lock.json');
  if (!fs.existsSync(lockPath)) {
    console.error('core.lock.json is missing.');
    process.exit(1);
  }
  const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
  const outputs = lock.outputs ?? {};
  const entries = Object.entries(outputs);
  if (entries.length === 0) {
    console.error('core.lock.json contains no output hashes.');
    process.exit(1);
  }
  const diffs = [];
  for (const [relPath, expectedHash] of entries) {
    const fullPath = path.join(MOBILE_ROOT, relPath);
    if (!fs.existsSync(fullPath)) {
      diffs.push(`MISSING: ${relPath}`);
      continue;
    }
    const actualHash = sha256(fs.readFileSync(fullPath, 'utf8'));
    if (actualHash !== expectedHash) {
      diffs.push(`HASH_MISMATCH: ${relPath}`);
    }
  }
  if (diffs.length > 0) {
    console.error('sync-core lock verification failed:\n' + diffs.join('\n'));
    process.exit(1);
  }
  console.log(`core.lock.json verified (${entries.length} hashed outputs).`);
}

function main() {
  if (VERIFY_LOCK_MODE) {
    verifyLockFile();
    return;
  }

  const generated = generateOutputs();

  if (CHECK_MODE) {
    const diffs = [];
    for (const [relPath, expected] of generated.entries()) {
      const fullPath = path.join(MOBILE_ROOT, relPath);
      if (!fs.existsSync(fullPath)) {
        diffs.push(`MISSING: ${relPath}`);
        continue;
      }
      const actual = fs.readFileSync(fullPath, 'utf8');
      if (actual !== expected) {
        diffs.push(`DRIFT: ${relPath}`);
      }
    }
    if (diffs.length > 0) {
      console.error('sync-core check failed:\n' + diffs.join('\n'));
      process.exit(1);
    }
    console.log(`sync-core check passed (${generated.size} files verified).`);
    return;
  }

  for (const [relPath, content] of generated.entries()) {
    const fullPath = path.join(MOBILE_ROOT, relPath);
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, content, 'utf8');
  }
  console.log(`Synced ${generated.size} files into src/core/, src/data/, and core.lock.json.`);
}

main();
